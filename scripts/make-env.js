/* Writes js/env.js, which gives the page its Supabase settings.
   Values come from .env on your computer, or from GitHub secrets when deploying.
   Run from the project folder:  node scripts/make-env.js */
const fs = require("fs");

const values = { ...process.env };
if (fs.existsSync(".env")) {
  for (const line of fs.readFileSync(".env", "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z_]+)\s*=\s*(.*?)\s*$/);
    if (match) values[match[1]] = match[2].replace(/^(['"])(.*)\1$/, "$2");
  }
}

const url = values.SUPABASE_URL;
const key = values.SUPABASE_KEY;

if (!url || !key) {
  console.error("Missing SUPABASE_URL or SUPABASE_KEY. Add them to .env or to the GitHub secrets.");
  process.exit(1);
}

// Everything in js/env.js is readable by anyone who opens the site.
function isSecretKey(value) {
  if (value.startsWith("sb_secret_")) return true;
  const payload = value.split(".")[1];
  if (!payload) return false;
  try {
    return JSON.parse(Buffer.from(payload, "base64url").toString()).role === "service_role";
  } catch {
    return false;
  }
}
if (isSecretKey(key)) {
  console.error("Refusing to continue: this is a secret key. Use the publishable (anon) key.");
  process.exit(1);
}

fs.writeFileSync(
  "js/env.js",
  `/* Generated by scripts/make-env.js. Do not edit or commit. */\nwindow.ENV = ${JSON.stringify({ SUPABASE_URL: url, SUPABASE_KEY: key })};\n`
);
console.log("Wrote js/env.js");
